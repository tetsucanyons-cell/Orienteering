# Excelファイル作成
wb = openpyxl.Workbook()
ws = wb.active
ws.title = "お気に入り物件一覧"

# カラム定義
columns = [
    "No.", "物件名", "住所", "最寄駅", "駅徒歩（分）",
    "家賃（万円）", "管理費（円）", "合計月額（円）",
    "敷金（万円）", "礼金（万円）",
    "間取り", "面積（m²）", "築年数（年）", "階数", "構造", "向き", "掲載状況"
]

# ヘッダースタイル
header_fill = PatternFill(start_color="2E4057", end_color="2E4057", fill_type="solid")
header_font = Font(color="FFFFFF", bold=True, name="Yu Gothic", size=10)
ended_fill = PatternFill(start_color="F0F0F0", end_color="F0F0F0", fill_type="solid")
ended_font = Font(color="999999", name="Yu Gothic", size=10)
normal_font = Font(name="Yu Gothic", size=10)
center_align = Alignment(horizontal="center", vertical="center", wrap_text=False)
left_align = Alignment(horizontal="left", vertical="center")

thin = Side(style="thin", color="CCCCCC")
border = Border(left=thin, right=thin, top=thin, bottom=thin)

# ヘッダー行
for col_idx, col_name in enumerate(columns, 1):
    cell = ws.cell(row=1, column=col_idx, value=col_name)
    cell.font = header_font
    cell.fill = header_fill
    cell.alignment = center_align
    cell.border = border

ws.row_dimensions[1].height = 20

# データ行
for row_idx, prop in enumerate(properties, 2):
    is_ended = prop["掲載状況"] == "掲載終了"
    total_monthly = int(prop["家賃（万円）"] * 10000) + prop["管理費（円）"]

    values = [
        row_idx - 1,
        prop["物件名"],
        prop["住所"],
        prop["最寄駅"],
        prop["駅徒歩（分）"],
        prop["家賃（万円）"],
        prop["管理費（円）"] if prop["管理費（円）"] > 0 else "-",
        total_monthly,
        prop["敷金（万円）"],
        prop["礼金（万円）"],
        prop["間取り"],
        prop["面積（m²）"],
        prop["築年数（年）"],
        prop["階数"],
        prop["構造"],
        prop["向き"],
        prop["掲載状況"],
    ]

    for col_idx, val in enumerate(values, 1):
        cell = ws.cell(row=row_idx, column=col_idx, value=val)
        cell.border = border
        cell.font = ended_font if is_ended else normal_font

        if col_idx == 2:  # 物件名
            cell.alignment = left_align
        elif col_idx == 3:  # 住所
            cell.alignment = left_align
        elif col_idx == 4:  # 最寄駅
            cell.alignment = left_align
        else:
            cell.alignment = center_align

        # 掲載状況セルの色
        if col_idx == 17:
            if is_ended:
                cell.fill = PatternFill(start_color="E8E8E8", end_color="E8E8E8", fill_type="solid")
                cell.font = Font(color="999999", bold=True, name="Yu Gothic", size=10)
            else:
                cell.fill = PatternFill(start_color="E8F5E9", end_color="E8F5E9", fill_type="solid")
                cell.font = Font(color="2E7D32", bold=True, name="Yu Gothic", size=10)

        # 掲載終了行の背景
        if is_ended and col_idx != 17:
            cell.fill = ended_fill

    ws.row_dimensions[row_idx].height = 18

# 列幅設定
col_widths = {
    1: 5,   # No.
    2: 22,  # 物件名
    3: 24,  # 住所
    4: 24,  # 最寄駅
    5: 12,  # 駅徒歩
    6: 12,  # 家賃
    7: 12,  # 管理費
    8: 14,  # 合計月額
    9: 12,  # 敷金
    10: 12, # 礼金
    11: 8,  # 間取り
    12: 12, # 面積
    13: 12, # 築年数
    14: 8,  # 階数
    15: 16, # 構造
    16: 10, # 向き
    17: 12, # 掲載状況
}
for col, width in col_widths.items():
    ws.column_dimensions[get_column_letter(col)].width = width

# ウィンドウ枠の固定（ヘッダー行）
ws.freeze_panes = "A2"

# オートフィルター
ws.auto_filter.ref = f"A1:{get_column_letter(len(columns))}1"

